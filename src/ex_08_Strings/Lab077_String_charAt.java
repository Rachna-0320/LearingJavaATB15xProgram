package ex_08_Strings;

public class Lab077_String_charAt {
    public static void main(String[] args) {

        String s = "Code" ;
        char c = s.charAt(3);
        System.out.println(c);

        System.out.println(s.charAt(0));

        String code = " .+Ja va";
        System.out.println(code.charAt(0));
        System.out.println(code.charAt(1));
        System.out.println(code.charAt(2));
        System.out.println(code.charAt(3));
        System.out.println(code.charAt(4));
        System.out.println(code.charAt(5));
        System.out.println(code.charAt(6));
    }
}
